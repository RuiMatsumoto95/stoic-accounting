describe('decodeCsvText', () => {
  it('UTF-8 はそのまま読む', () => {
    const bytes = new TextEncoder().encode('日付,借方科目\r\n2026/4/1,現金\r\n')
    expect(decodeCsvText(bytes)).toEqual({ text: '日付,借方科目\r\n2026/4/1,現金\r\n', encoding: 'utf-8' })
  })

  it('UTF-8 の BOM は取り除く', () => {
    const body = new TextEncoder().encode('現金')
    const bytes = Uint8Array.from([0xef, 0xbb, 0xbf, ...body])
    expect(decodeCsvText(bytes)).toEqual({ text: '現金', encoding: 'utf-8' })
  })

  it('ASCII だけなら UTF-8 として読む', () => {
    expect(decodeCsvText(new TextEncoder().encode('a,b,1'))).toEqual({ text: 'a,b,1', encoding: 'utf-8' })
  })

  it('UTF-8 として読めなければ Shift-JIS として読む（「現金」= 8C BB 8B E0）', () => {
    const bytes = Uint8Array.from([0x8c, 0xbb, 0x8b, 0xe0])
    expect(decodeCsvText(bytes)).toEqual({ text: '現金', encoding: 'shift_jis' })
  })

  it('ArrayBuffer も受け付ける', () => {
    const buffer = Uint8Array.from([0x8c, 0xbb, 0x8b, 0xe0]).buffer
    expect(decodeCsvText(buffer).text).toBe('現金')
  })

  it('弥生を模した Shift-JIS の CSV 全体を読める', () => {
    const { text, encoding } = decodeCsvText(YAYOI_SJIS)
    expect(encoding).toBe('shift_jis')
    expect(text).toContain('"R.08/04/01","現金"')
    expect(text).toContain('事務用品購入')
  })
})

describe('prepareCsvRows', () => {
  const data = [['2000', 'a'], ['2110', 'b']]

  it('独自形式は、従来どおり先頭行を見出し行として捨てる', () => {
    expect(prepareCsvRows('custom', [['日付', '借方科目'], ['2026/4/1', '現金']])).toEqual({
      ok: true,
      rows: [['2026/4/1', '現金']],
    })
  })

  it('弥生形式は、先頭行も仕訳として残す', () => {
    expect(prepareCsvRows('yayoi', data)).toEqual({ ok: true, rows: data })
  })

  it('弥生形式で、識別フラグの前後に空白があっても仕訳として扱う', () => {
    expect(prepareCsvRows('yayoi', [[' 2000 ', 'a']]).ok).toBe(true)
  })

  it.each<[string, string[][]]>([
    ['日本語の見出し', [['識別フラグ', '伝票No'], ['2000', '1']]],
    ['英字の見出し', [['flag', 'no']]],
    ['空の先頭セル', [['', 'x']]],
    ['3桁の数字', [['200', 'x']]],
  ])('弥生形式の先頭行が見出し行らしければエラー: %s', (_label, rows) => {
    const result = prepareCsvRows('yayoi', rows)
    expect(result.ok).toBe(false)
    if (!result.ok) expect(result.message).toContain('見出し行')
  })

  it('エラーメッセージに先頭の値を（長ければ省略して）示す', () => {
    const result = prepareCsvRows('yayoi', [['識別フラグ']])
    expect(!result.ok && result.message).toContain('「識別フラグ」')
    const long = prepareCsvRows('yayoi', [['あ'.repeat(30)]])
    expect(!long.ok && long.message).toContain('あ'.repeat(20) + '…')
  })

  it('空の入力は、どちらの形式でも空の行を返す', () => {
    expect(prepareCsvRows('custom', [])).toEqual({ ok: true, rows: [] })
    expect(prepareCsvRows('yayoi', [])).toEqual({ ok: true, rows: [] })
  })
})

// アップロード画面（CsvUploader）が行う処理の流れのうち、ブラウザ以外の部分をつなげて確認する
describe('弥生の出力 CSV（Shift-JIS・見出し行なし・和暦）を取り込む流れ', () => {
  it('デコード → パース → 前処理 → 弥生パーサーで、仕訳が欠落せず取り込める', async () => {
    resetFakeDb()
    const { text } = decodeCsvText(YAYOI_SJIS)
    const parsed = Papa.parse<string[]>(text, { header: false, skipEmptyLines: true })
    const prepared = prepareCsvRows('yayoi', parsed.data)
    expect(prepared.ok).toBe(true)
    if (!prepared.ok) return

    const { rows, errors, warnings } = await parseYayoiCsvFile(prepared.rows, 1, 'fixture-company')

    expect(errors).toEqual([])
    expect(rows).toHaveLength(2) // 先頭の仕訳も含まれる
    expect(rows[0]).toMatchObject({
      raw_date: '2026-04-01',
      raw_debit_amount: 500000,
      predicted_account_id: ID.cash,
      counter_account_id: ID.sales,
      raw_description: '1月売上入金',
    })
    expect(rows[1]).toMatchObject({
      raw_date: '2026-04-01',
      predicted_account_id: ID.supplies,
      counter_account_id: ID.bank,
      credit_sub_account_id: ID.bankA,
      raw_description: '事務用品購入',
    })
    // 複合仕訳（2110・2101）は警告つきでスキップされる。行番号は見出し行なしの数え方（先頭が 1 行目）
    expect(warnings).toEqual([
      { row: 2, message: '複合仕訳のためスキップしました' },
      { row: 3, message: '複合仕訳のためスキップしました' },
    ])
  })
})
